int pixfont_pixel(char character, int x, int y) {
    uint32_t index = (uint32_t)(unsigned char)character;
    if (x < 0 || x >= PIXFONT_WIDTH || y < 0 || y >= PIXFONT_HEIGHT) return 0;
    if (index < 32 || index > 126) return 0;

    int source_y = y * 3 / 5;
    if (character == ',' || character == '_' || character == '.' ||
        character == '!' || character == '/' || character == '(' ||
        character == ')' || character == ';') source_y = y < 13 ? y : 12;
    return (font[index - 32].rows[source_y] >> (7 - x)) & 1;
}
